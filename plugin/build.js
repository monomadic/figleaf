// Development build only. The plugin runtime never writes files.
const fs = require('node:fs');
const path = require('node:path');
const read = name => fs.readFileSync(path.join(__dirname, name), 'utf8');
const bundle = '// Generated by node plugin/build.js; edit source files instead.\n' +
  'const __html__ = ' + JSON.stringify(read('ui.html')) + ';\n' + read('exporter.js') + '\n' + read('code.js');
if (process.argv.includes('--check')) {
  if (read('dist/code.js') !== bundle) throw Error('Plugin bundle is stale. Run node plugin/build.js.');
} else {
  fs.mkdirSync(path.join(__dirname, 'dist'), { recursive: true });
  fs.writeFileSync(path.join(__dirname, 'dist/code.js'), bundle);
}
